"""Модуль учёта успеваемости студентов."""


def average(marks):
    """Средний балл по списку оценок."""
    return sum(marks) / len(marks)


def grade_name(mark):
    """Текстовое название оценки."""
    names = {5: "отлично", 4: "хорошо", 3: "удовлетворительно", 2: "неудовлетворительно"}
    return names[mark]
